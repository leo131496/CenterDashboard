const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');

(async()=>{
  const output=path.resolve(__dirname,'../test-results');await fs.mkdir(output,{recursive:true});
  const launch={headless:true};if(process.env.CHROME_PATH)launch.executablePath=process.env.CHROME_PATH;
  const browser=await chromium.launch(launch);
  const page=await browser.newPage({viewport:{width:1512,height:1060},acceptDownloads:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.DEMO_URL||'http://127.0.0.1:4173');
  const wait=()=>page.waitForFunction(()=>document.querySelectorAll('.kpi-card').length===4);
  await wait();
  const pageNames=['运营总览','课程分析','智库分析','考试分析','学员成长','内容治理'];
  for(let i=0;i<pageNames.length;i++){
    await page.getByRole('tab',{name:pageNames[i],exact:true}).click();
    await page.waitForFunction(label=>document.querySelector('.tab.active')?.textContent===label,pageNames[i]);
    assert.equal(await page.locator('.kpi-card').count(),4);
    assert(await page.locator('#data-table tbody tr').count()>0);
    await page.screenshot({path:path.join(output,`desktop-${i+1}.png`),fullPage:true});
    await page.locator('.kpi-card').first().click();assert(await page.locator('#detail-dialog').isVisible());
    await page.getByRole('button',{name:'查看相关明细'}).click();
    if(await page.locator('#detail-dialog').isVisible())await page.getByRole('button',{name:'关闭弹窗'}).click();
  }
  await page.getByRole('tab',{name:'运营总览',exact:true}).click();
  await page.locator('#region').selectOption('华东');
  assert.equal(await page.locator('#organization option').count(),3);
  await page.locator('#organization').selectOption('ORG1');
  await page.locator('#identity').selectOption('经销商');
  assert.match(await page.locator('#scope-note').innerText(),/华东.*启程.*经销商/);
  const filteredValue=await page.locator('.kpi-figure strong').first().textContent();
  assert(Number(filteredValue.replaceAll(',',''))<360);
  await page.getByRole('button',{name:'重置筛选'}).click();
  assert.equal(await page.locator('#organization option').count(),13);
  await page.getByRole('button',{name:'近7天',exact:true}).click();
  assert.equal(await page.locator('#start-date').inputValue(),'2026-10-17');
  await page.locator('#start-date').fill('2026-10-24');await page.locator('#start-date').dispatchEvent('change');
  assert(await page.locator('#filter-error').isVisible());
  await page.getByRole('button',{name:'重置筛选'}).click();
  const search=page.locator('#table-search');await search.fill('Terra');
  assert.equal(await page.locator('#data-table tbody tr').count(),1);
  const downloadWait=page.waitForEvent('download');await page.getByRole('button',{name:'导出明细',exact:true}).click();
  const download=await downloadWait;const file=await download.path();const csv=await fs.readFile(file,'utf8');
  assert(csv.includes('全部为模拟数据'));assert(csv.includes('Terra'));assert(!csv.includes('Symmetry'));
  assert.match(download.suggestedFilename(),/\.csv$/);
  await page.locator('[data-detail="course"]').click();
  assert.match(await page.locator('#dialog-title').innerText(),/Terra/);
  await page.getByRole('button',{name:'关闭弹窗'}).click();
  await search.fill('不存在的课程');assert.match(await page.locator('#data-table').innerText(),/没有找到/);
  await search.fill('');
  await page.getByRole('button',{name:'分配人次',exact:false}).click();
  assert.equal(await page.locator('[data-sort="assigned"] span').textContent(),'↓');
  await page.getByRole('button',{name:'下一页'}).click();assert.match(await page.locator('.pagination').innerText(),/2/);
  await page.getByRole('tab',{name:'考试分析',exact:true}).click();
  await page.getByRole('button',{name:'错题分析',exact:true}).click();
  assert.match(await page.locator('.table-panel h2').innerText(),/错题/);
  await page.locator('[data-detail="question"]').first().click();assert.match(await page.locator('#dialog-content').innerText(),/参考答案/);
  await page.getByRole('button',{name:'关闭弹窗'}).click();
  await page.getByRole('tab',{name:'学员成长',exact:true}).click();
  await page.getByRole('button',{name:'企业排行',exact:true}).click();
  assert.match(await page.locator('.table-panel h2').innerText(),/企业/);
  await page.locator('[data-detail="organization"]').first().click();assert.match(await page.locator('#dialog-content').innerText(),/未学习天数/);
  await page.getByRole('button',{name:'关闭弹窗'}).click();
  await page.getByRole('tab',{name:'内容治理',exact:true}).click();
  await page.locator('#table-category').selectOption('待审核');
  assert(await page.locator('#data-table tbody tr').count()>0);
  await page.locator('[data-detail="submission"]').first().click();assert.match(await page.locator('#dialog-content').innerText(),/关联协议/);
  await page.getByRole('button',{name:'关闭弹窗'}).click();
  await page.locator('[data-action="coverage"]').first().click();assert.match(await page.locator('#dialog-content').innerText(),/11/);
  await page.keyboard.press('Escape');assert(!await page.locator('#detail-dialog').isVisible());
  await page.getByRole('button',{name:'重置筛选'}).click();
  await page.locator('#start-date').fill('2026-04-01');await page.locator('#start-date').dispatchEvent('change');
  await page.locator('#end-date').fill('2026-04-01');await page.locator('#end-date').dispatchEvent('change');
  assert.match(await page.locator('#data-table').innerText(),/没有找到符合条件/);
  await page.getByRole('button',{name:'重置筛选'}).click();
  await page.getByRole('tab',{name:'运营总览',exact:true}).click();
  await page.locator('.chart-point').first().focus();assert(await page.locator('.chart-tooltip').isVisible());
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
  mobile.on('pageerror',e=>errors.push(e.message));await mobile.goto(process.env.DEMO_URL||'http://127.0.0.1:4173');
  for(let i=0;i<pageNames.length;i++){
    await mobile.getByRole('tab',{name:pageNames[i],exact:true}).click();
    await mobile.waitForFunction(label=>document.querySelector('.tab.active')?.textContent===label,pageNames[i]);
    const overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    assert.equal(overflow,false,'Mobile document must not overflow: '+pageNames[i]);
    await mobile.screenshot({path:path.join(output,`mobile-${i+1}.png`),fullPage:true});
  }
  await mobile.getByRole('button',{name:'展开导航'}).click();assert(await mobile.locator('.sidebar').evaluate(e=>e.classList.contains('open')));
  await mobile.locator('[data-source="courses"]').click();assert(await mobile.locator('#detail-dialog').isVisible());
  await mobile.getByRole('button',{name:'打开分析',exact:false}).click();
  await mobile.waitForFunction(()=>document.querySelector('.tab.active')?.textContent==='课程分析');
  assert.deepEqual(errors,[]);
  await browser.close();console.log('PASS: six desktop/mobile pages, filters, drilldowns, search, sorting, pagination, CSV, empty states, dialogs and tooltips.');
})().catch(e=>{console.error(e);process.exit(1);});
